def train_model(model, train_loader, val_loader, epochs=8, lr=1e-3, weight_decay=1e-4,
                 class_weights=None, model_name="model"):
    model = model.to(device)
    criterion = nn.CrossEntropyLoss(weight=class_weights)
    optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=weight_decay)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode="min", factor=0.5, patience=2)

    history = {"train_loss": [], "train_acc": [], "val_loss": [], "val_acc": []}
    best_val_loss = float("inf")
    best_state = None

    for epoch in range(epochs):
        # ---- train ----
        model.train()
        running_loss, running_correct, n = 0.0, 0, 0
        for xb, yb in train_loader:
            xb, yb = xb.to(device), yb.to(device)
            optimizer.zero_grad()
            out = model(xb)
            loss = criterion(out, yb)
            loss.backward()
            optimizer.step()

            running_loss += loss.item() * xb.size(0)
            running_correct += (out.argmax(1) == yb).sum().item()
            n += xb.size(0)
        train_loss, train_acc = running_loss / n, running_correct / n

        # ---- validate ----
        model.eval()
        v_loss, v_correct, vn = 0.0, 0, 0
        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(device), yb.to(device)
                out = model(xb)
                loss = criterion(out, yb)
                v_loss += loss.item() * xb.size(0)
                v_correct += (out.argmax(1) == yb).sum().item()
                vn += xb.size(0)
        val_loss, val_acc = v_loss / vn, v_correct / vn
        scheduler.step(val_loss)

        history["train_loss"].append(train_loss); history["train_acc"].append(train_acc)
        history["val_loss"].append(val_loss); history["val_acc"].append(val_acc)

        print(f"[{model_name}] epoch {epoch+1}/{epochs} "
              f"train_loss={train_loss:.4f} train_acc={train_acc:.4f} "
              f"val_loss={val_loss:.4f} val_acc={val_acc:.4f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_state = copy.deepcopy(model.state_dict())

    model.load_state_dict(best_state)
    return model, history


def plot_history(history, title):
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    axes[0].plot(history["train_loss"], label="train")
    axes[0].plot(history["val_loss"], label="val")
    axes[0].set_title(f"{title} — Loss"); axes[0].set_xlabel("epoch"); axes[0].legend()

    axes[1].plot(history["train_acc"], label="train")
    axes[1].plot(history["val_acc"], label="val")
    axes[1].set_title(f"{title} — Accuracy"); axes[1].set_xlabel("epoch"); axes[1].legend()
    plt.tight_layout(); plt.show()


@torch.no_grad()
def get_predictions(model, loader):
    model.eval()
    all_probs, all_preds, all_labels = [], [], []
    for xb, yb in loader:
        xb = xb.to(device)
        out = model(xb)
        probs = torch.softmax(out, dim=1)[:, 1]
        preds = out.argmax(1).cpu().numpy()
        all_probs.extend(probs.cpu().numpy())
        all_preds.extend(preds)
        all_labels.extend(yb.numpy())
    return np.array(all_labels), np.array(all_preds), np.array(all_probs)


def evaluate(model, loader, model_name="model", plot=True):
    y_true, y_pred, y_prob = get_predictions(model, loader)

    metrics = {
        "accuracy": (y_true == y_pred).mean(),
        "precision": precision_score(y_true, y_pred),
        "recall": recall_score(y_true, y_pred),
        "f1": f1_score(y_true, y_pred),
        "roc_auc": roc_auc_score(y_true, y_prob),
    }

    print(f"\n=== {model_name} — Test Set Report ===")
    print(classification_report(y_true, y_pred, target_names=CLASS_NAMES))
    for k, v in metrics.items():
        print(f"{k:>10}: {v:.4f}")

    if plot:
        fig, axes = plt.subplots(1, 2, figsize=(11, 4))
        cm = confusion_matrix(y_true, y_pred)
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                    xticklabels=CLASS_NAMES, yticklabels=CLASS_NAMES, ax=axes[0])
        axes[0].set_title(f"{model_name} — Confusion Matrix")
        axes[0].set_xlabel("Predicted"); axes[0].set_ylabel("True")

        fpr, tpr, _ = roc_curve(y_true, y_prob)
        axes[1].plot(fpr, tpr, label=f"AUC = {metrics['roc_auc']:.3f}")
        axes[1].plot([0, 1], [0, 1], "--", color="gray")
        axes[1].set_title(f"{model_name} — ROC Curve")
        axes[1].set_xlabel("False Positive Rate"); axes[1].set_ylabel("True Positive Rate")
        axes[1].legend()
        plt.tight_layout(); plt.show()

    return metrics

